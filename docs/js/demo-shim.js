/* The pre-computed responses only exist on the 1,000 DOE grid points, so the
   operating point is snapped BEFORE each run and the sliders are moved to
   match. Without this the UI would show one condition and the data another. */
function installDemoSnapping() {
  const snap = () => {
    if (!DEMO.manifest) return;
    const s = DEMO.snapPoint({
      dose_cm2: APP.state.dose, energy_keV: APP.state.energy,
      anneal_temp_C: APP.state.temp, anneal_time_sec: APP.state.time,
    });
    APP.state.dose = s.dose_cm2; APP.state.energy = s.energy_keV;
    APP.state.temp = s.anneal_temp_C; APP.state.time = s.anneal_time_sec;
    if (typeof Predict !== 'undefined' && Predict.syncSliders && document.getElementById('sDose')) {
      Predict.syncSliders(); Predict.syncLabels();
    }
  };
  const wrap = (obj, fn) => {
    if (typeof obj === 'undefined' || !obj[fn]) return;
    const orig = obj[fn].bind(obj);
    obj[fn] = async (...a) => { snap(); return orig(...a); };
  };
  wrap(typeof Predict !== 'undefined' ? Predict : undefined, 'run');
  wrap(typeof WhatIf !== 'undefined' ? WhatIf : undefined, 'run');
  wrap(typeof Robust !== 'undefined' ? Robust : undefined, 'run');
}

