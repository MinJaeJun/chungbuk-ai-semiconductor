/* ==========================================================================
   demo-shim.js  —  STATIC DEMO ONLY (GitHub Pages)
   --------------------------------------------------------------------------
   The real app talks to a FastAPI backend that runs the trained surrogate.
   GitHub Pages serves static files only, so this shim replaces the network
   layer with pre-computed responses generated by export_static.py.

   What stays identical to the live app:
     - every number comes from the same trained model, exported verbatim
     - Data Explorer / XAI / Model Validation / variation reference are 1:1
     - MODE A optimizer is recomputed here from the same 1,000 measured rows

   What is restricted (and told to the user, never hidden):
     - process inputs snap to the 1,000 TCAD DOE grid points
     - MODE B snaps to the nearest pre-computed target/weight scenario
     - robustness uses one tolerance preset (Typical)

   This file is NOT loaded by the local FastAPI build.
   ========================================================================== */
'use strict';

const DEMO = {
  base: 'api',
  manifest: null,
  cache: new Map(),

  async json(path) {
    if (DEMO.cache.has(path)) return DEMO.cache.get(path);
    const p = fetch(`${DEMO.base}/${path}`).then(r => {
      if (!r.ok) throw new Error(`정적 데모 데이터를 찾을 수 없습니다: ${path}`);
      return r.json();
    });
    DEMO.cache.set(path, p);
    return p;
  },

  /* nearest DOE level for each process input */
  snapPoint(b) {
    const lv = DEMO.manifest.levels;
    return {
      dose_cm2: nearest(lv.dose_cm2, b.dose_cm2),
      energy_keV: nearest(lv.energy_keV, b.energy_keV),
      anneal_temp_C: nearest(lv.anneal_temp_C, b.anneal_temp_C),
      anneal_time_sec: nearest(lv.anneal_time_sec, b.anneal_time_sec),
    };
  },

  idx(arr, v) {
    let best = 0;
    for (let i = 1; i < arr.length; i++) {
      if (Math.abs(arr[i] - v) < Math.abs(arr[best] - v)) best = i;
    }
    return best;
  },

  key(b) {
    const lv = DEMO.manifest.levels;
    const s = DEMO.snapPoint(b);
    return {
      d: DEMO.idx(lv.dose_cm2, s.dose_cm2),
      e: DEMO.idx(lv.energy_keV, s.energy_keV),
      t: DEMO.idx(lv.anneal_temp_C, s.anneal_temp_C),
      s: DEMO.idx(lv.anneal_time_sec, s.anneal_time_sec),
    };
  },

  /* ---------------------------------------------------------------- MODE A */
  /* Recomputed in the browser from the same 1,000 measured TCAD rows the
     Explorer already loads. No model needed - MODE A only ranks measured
     values - so the result is identical to the backend, not an approximation.
     export_static.py asserts that equivalence at build time. */
  optimizeDoe(req) {
    const cols = APP.points.columns;
    const tb = APP.meta.dataset.target_bounds;
    const n = cols.dose_cm2.length;
    const xjSpan = tb.xj_final_um.max - tb.xj_final_um.min;
    const rshLo = tb.rsh_final_ohm_sq.min, rshHi = tb.rsh_final_ohm_sq.max;
    const wx = req.w_xj, wr = req.w_rsh, tot = (wx + wr) || 1;

    const locks = {
      dose_cm2: req.lock_dose_cm2, energy_keV: req.lock_energy_keV,
      anneal_temp_C: req.lock_anneal_temp_C, anneal_time_sec: req.lock_anneal_time_sec,
    };
    const rows = [];
    for (let i = 0; i < n; i++) {
      let ok = true;
      for (const [k, v] of Object.entries(locks)) {
        if (v !== null && v !== undefined && Math.abs(cols[k][i] - v) > Math.abs(v) * 1e-6 + 1e-9) { ok = false; break; }
      }
      if (!ok) continue;
      const xj = cols.xj_final_um[i], rsh = cols.rsh_final_ohm_sq[i];
      const err = Math.abs(xj - req.target_xj_um);
      const score = (wx * (err / xjSpan) + wr * Math.max(0, (rsh - rshLo) / (rshHi - rshLo))) / tot;
      let feas = err <= req.tolerance_um;
      if (req.rsh_mode === 'constraint' && req.rsh_max != null) feas = feas && rsh <= req.rsh_max;
      rows.push({ i, xj, rsh, err, score, feas });
    }
    rows.sort((a, b) => (a.feas === b.feas ? a.score - b.score : (a.feas ? -1 : 1)));

    const recipeOf = (r) => ({
      dose_cm2: Number(cols.dose_cm2[r.i].toPrecision(4)),
      energy_keV: Math.round(cols.energy_keV[r.i] * 100) / 100,
      anneal_temp_C: Math.round(cols.anneal_temp_C[r.i] * 10) / 10,
      anneal_time_sec: Math.round(cols.anneal_time_sec[r.i] * 10) / 10,
    });
    const recipes = rows.slice(0, req.top_k).map((r, k) => ({
      rank: k + 1,
      source: 'TCAD measured (validated DOE point)',
      recipe: recipeOf(r),
      predicted: {
        xj_implant_um: cols.xj_implant_um[r.i], xj_final_um: r.xj,
        delta_xj_um: cols.delta_xj_um[r.i], rsh_final_ohm_sq: r.rsh,
      },
      xj_error_um: r.err, score: r.score, feasible: r.feas,
      run_id: APP.points.run_id ? APP.points.run_id[r.i] : r.i + 1,
      surrogate_check: { xj_final_um: r.xj, rsh_final_ohm_sq: r.rsh, xj_abs_error_um: 0, rsh_abs_error_ohm_sq: 0 },
    }));

    const pool = rows.some(r => r.feas) ? rows.filter(r => r.feas) : rows;
    const byErr = pool.slice().sort((a, b) => (a.err - b.err) || (a.rsh - b.rsh));
    const pareto = [];
    let bestRsh = Infinity;
    for (const r of byErr) {
      if (r.rsh < bestRsh - 1e-12) {
        pareto.push({ recipe: recipeOf(r), xj_final_um: r.xj, xj_error_um: r.err, rsh_final_ohm_sq: r.rsh, score: r.score, feasible: r.feas });
        bestRsh = r.rsh;
      }
    }
    const cloud = rows.slice().sort((a, b) => a.score - b.score).slice(0, 1200);
    const xs = rows.map(r => r.xj), rs = rows.map(r => r.rsh);
    return {
      mode: 'doe',
      mode_label: 'MODE A · Validated DOE Search',
      verification_warning: null, verification_warning_ko: null,
      objective: {
        target_xj_um: req.target_xj_um, tolerance_um: req.tolerance_um,
        rsh_mode: req.rsh_mode, rsh_max: req.rsh_max, w_xj: wx, w_rsh: wr,
        constraint_note: req.rsh_mode === 'constraint' && req.rsh_max != null ? `Rsh <= ${req.rsh_max} ohm/sq` : null,
        formula: 'score = (w_xj * |Xj-Xj_target|/range(Xj) + w_rsh * (Rsh-min)/range(Rsh)) / (w_xj+w_rsh)',
      },
      search: { candidates_evaluated: rows.length, feasible_count: rows.filter(r => r.feas).length, locks: {} },
      recipes, pareto,
      cloud: { xj_error_um: cloud.map(r => r.err), rsh_final_ohm_sq: cloud.map(r => r.rsh) },
      achievable_range: { xj_final_um: [Math.min(...xs), Math.max(...xs)], rsh_final_ohm_sq: [Math.min(...rs), Math.max(...rs)] },
      insights: [DEMO.noteCard(
        'MODE A 결과는 정적 데모에서도 정확합니다',
        'MODE A는 실제 TCAD 1,000 run의 측정값을 정렬하는 연산이라 모델이 필요 없습니다. ' +
        '이 순위표는 브라우저가 계산했지만 빌드 시 백엔드 결과와 run_id 단위까지 일치하는지 검증합니다. ' +
        '다만 문장형 인사이트 카드는 백엔드에서 생성되므로 로컬 실행 시에만 표시됩니다.',
        'MODE A ranks measured TCAD values, so no model is required; the browser-side ' +
        'ranking is verified against the backend at build time. Narrative insight cards ' +
        'are generated server-side and appear only in the local build.'
      )],
      _demo_exact: true,
    };
  },

  noteCard(titleKo, textKo, textEn) {
    return {
      level: 'ENGINEERING VERIFICATION REQUIRED',
      title_ko: titleKo, title_en: titleKo,
      text_ko: textKo, text_en: textEn || '',
      evidence: { demo: true },
    };
  },

  /* Yield / Cpk are recomputed from the stored Monte-Carlo histogram so the
     spec sliders stay live even though the sampling itself is pre-computed. */
  respec(rb, spec) {
    const out = JSON.parse(JSON.stringify(rb));
    const lsl = spec.target_xj_um - spec.tolerance_um;
    const usl = spec.target_xj_um + spec.tolerance_um;
    const frac = (dist, lo, hi) => {
      const h = dist.histogram;
      const total = h.counts.reduce((a, b) => a + b, 0) || 1;
      let acc = 0;
      for (let i = 0; i < h.counts.length; i++) {
        const a = h.edges[i], b = h.edges[i + 1];
        const ov = Math.max(0, Math.min(b, hi) - Math.max(a, lo));
        if (ov > 0) acc += h.counts[i] * (ov / (b - a));
      }
      return acc / total * 100;
    };
    const xj = out.distribution.xj_final_um, rsh = out.distribution.rsh_final_ohm_sq;
    const yXj = frac(xj, lsl, usl);
    const yRsh = spec.rsh_max != null ? frac(rsh, -Infinity, spec.rsh_max) : null;
    out.spec = { target_xj_um: spec.target_xj_um, tolerance_um: spec.tolerance_um, lsl, usl, rsh_max: spec.rsh_max ?? null };
    out.yield = { xj_pct: yXj, rsh_pct: yRsh, joint_pct: yRsh === null ? yXj : (yXj / 100) * (yRsh / 100) * 100 };
    out.cpk = {
      xj: xj.std > 0 ? Math.min(usl - xj.mean, xj.mean - lsl) / (3 * xj.std) : null,
      rsh: spec.rsh_max != null && rsh.std > 0 ? (spec.rsh_max - rsh.mean) / (3 * rsh.std) : null,
    };
    out._demo_respec = true;
    return out;
  },
};

/* ----------------------------------------------------------- API override */
(function patchApi() {
  const GET = {
    '/api/meta': 'meta.json',
    '/api/dataset/summary': 'dataset_summary.json',
    '/api/dataset/points': 'dataset_points.json',
    '/api/xai/global': 'xai_global.json',
    '/api/validation': 'validation.json',
    '/api/variation': 'variation.json',
    '/api/health': null,
  };

  API.get = async (path) => {
    if (path === '/api/health') return { status: 'ok', model_trained: true, llm: { enabled: false, provider: null }, demo: true };
    const f = GET[path];
    if (!f) throw new Error(`정적 데모에서 지원하지 않는 요청입니다: ${path}`);
    return DEMO.json(f);
  };

  API.post = async (path, body) => {
    if (!DEMO.manifest) DEMO.manifest = await DEMO.json('manifest.json');

    if (path === '/api/predict') {
      const k = DEMO.key(body);
      const bundle = await DEMO.json(`predict/d${k.d}e${k.e}.json`);
      return bundle[`${k.t}_${k.s}`];
    }
    if (path === '/api/whatif') {
      const k = DEMO.key(body);
      const rest = { dose_cm2: `${k.e}_${k.t}_${k.s}`, energy_keV: `${k.d}_${k.t}_${k.s}`,
                     anneal_temp_C: `${k.d}_${k.e}_${k.s}`, anneal_time_sec: `${k.d}_${k.e}_${k.t}` }[body.parameter];
      const bundle = await DEMO.json(`whatif/${body.parameter}.json`);
      return bundle[rest];
    }
    if (path === '/api/robust') {
      const k = DEMO.key(body);
      const bundle = await DEMO.json(`robust/d${k.d}e${k.e}.json`);
      return DEMO.respec(bundle[`${k.t}_${k.s}`], body);
    }
    if (path === '/api/optimize') {
      if (body.mode === 'doe') {
        const r = DEMO.optimizeDoe(body);
        if (body.robust_rerank) r.robust = null;   // needs live Monte-Carlo
        return r;
      }
      const m = DEMO.manifest.optimize_ai;
      const ti = DEMO.idx(m.targets, body.target_xj_um);
      const wi = DEMO.idx(m.weights, body.w_xj);
      const bundle = await DEMO.json(`optimize_ai/w${wi}.json`);
      const base = bundle[String(ti)];
      const r = JSON.parse(JSON.stringify(base));
      // Re-apply the user's tolerance / Rsh limit to the pre-computed pool.
      r.recipes.forEach(x => {
        x.feasible = x.xj_error_um <= body.tolerance_um &&
          (body.rsh_mode !== 'constraint' || body.rsh_max == null || x.predicted.rsh_final_ohm_sq <= body.rsh_max);
      });
      r.recipes.sort((a, b) => (a.feasible === b.feasible ? a.score - b.score : (a.feasible ? -1 : 1)));
      r.recipes = r.recipes.slice(0, body.top_k).map((x, i) => Object.assign(x, { rank: i + 1 }));
      r.objective.tolerance_um = body.tolerance_um;
      r.objective.rsh_mode = body.rsh_mode;
      r.objective.rsh_max = body.rsh_max ?? null;
      r.search.feasible_count = r.recipes.filter(x => x.feasible).length;
      r._demo_snapped = { target: m.targets[ti], w_xj: m.weights[wi] };
      if (body.robust_rerank) r.robust = null;
      return r;
    }
    if (path === '/api/insight/llm') {
      return { enabled: false, provider: null, text: null, note: '정적 데모에서는 LLM 확장을 사용할 수 없습니다.' };
    }
    throw new Error(`정적 데모에서 지원하지 않는 요청입니다: ${path}`);
  };
})();

